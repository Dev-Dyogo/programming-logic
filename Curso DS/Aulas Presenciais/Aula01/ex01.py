# Objetivo: trabalhar variáveis e diferentes tipos de dados em Python.


nome = "João da Silva"  # Cria uma variável chamada nome e armazena um texto.

idade = 20  # Cria a variável idade e armazena um número inteiro.

telefone = "(75) 99999-9999"  # Telefone é armazenado como texto, pois não será usado em cálculos.

cpf = "123.456.789-00"  # CPF também é armazenado como texto para preservar pontos e zeros.

rg = "12.345.678-9"  # RG é armazenado como texto pelo mesmo motivo.

endereco = "Rua das Flores, 100"  # Armazena o endereço da pessoa como texto.

sexo = "Masculino"  # Armazena a informação referente ao sexo como texto.


print("Nome:", nome)  # Exibe o conteúdo da variável nome.

print("Idade:", idade)  # Exibe a idade.

print("Telefone:", telefone)  # Exibe o telefone.

print("CPF:", cpf)  # Exibe o CPF.

print("RG:", rg)  # Exibe o RG.

print("Endereço:", endereco)  # Exibe o endereço.

print("Sexo:", sexo)  # Exibe o sexo.